UPDATE public.premium_feature_policy
   SET free_preview_quota = 1, updated_at = NOW()
 WHERE feature_key = 'retrograde_alerts';

UPDATE public.premium_feature_policy
   SET free_preview_quota = 1, updated_at = NOW()
 WHERE feature_key = 'date_planner';

UPDATE public.premium_feature_policy
   SET free_preview_quota = 1, updated_at = NOW()
 WHERE feature_key = 'tarot_monthly';

UPDATE public.premium_feature_policy
   SET free_preview_quota = 1, updated_at = NOW()
 WHERE feature_key = 'tarot_cosmic';

-- -----------------------------------------------------------------------------
-- 3) Self-verification (a migration that changes privileges must prove itself
--    — same house rule as 20260903000003). Asserts the CATALOG this change
--    claims to produce — rows, quotas, classes, counts — refusing to commit
--    anything else.
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  v_expected TEXT[] := ARRAY[
    'natal_chart', 'conversation_guide', 'synastry',
    'daily_horoscope', 'monthly_horoscope', 'lucky_days',
    'planetary_transits', 'retrograde_alerts',
    'date_planner', 'tarot_monthly', 'tarot_cosmic', 'tarot'
  ];
  v_expected_class CONSTANT TEXT[] := ARRAY[
    'server_metered_ui',   -- natal_chart
    'server_metered_ui',   -- conversation_guide
    'server_metered_ui',   -- synastry
    'server_metered_ui',   -- daily_horoscope
    'server_metered_ui',   -- monthly_horoscope
    'server_metered_ui',   -- lucky_days
    'public_content',      -- planetary_transits
    'public_content',      -- retrograde_alerts
    'server_metered_ui',   -- date_planner
    'server_enforced_data',-- tarot_monthly
    'server_enforced_data',-- tarot_cosmic
    'server_enforced_data' -- tarot (alias of tarot_monthly)
  ];
  v_missing TEXT;
  v_bad RECORD;
  v_count INT;
BEGIN
  IF array_length(v_expected, 1) <> array_length(v_expected_class, 1) THEN
    RAISE EXCEPTION 'JUNO-06 self-check: key/class arrays out of sync';
  END IF;

  SELECT f INTO v_missing
    FROM unnest(v_expected) AS f
   WHERE NOT EXISTS (
     SELECT 1 FROM public.premium_feature_policy p WHERE p.feature_key = f
   )
   LIMIT 1;
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION 'JUNO-06 self-check: policy row missing: %', v_missing;
  END IF;

  -- The honest classes, one by one. A drift here is the exact security
  -- theater this column exists to prevent: a feature labeled
  -- server_enforced_data whose result the APK can still produce.
  FOR v_bad IN
    SELECT feature_key, enforcement_class
      FROM public.premium_feature_policy
     WHERE feature_key = ANY (v_expected)
  LOOP
    IF v_bad.enforcement_class IS DISTINCT FROM
       v_expected_class[array_position(v_expected, v_bad.feature_key)] THEN
      RAISE EXCEPTION
        'JUNO-06 self-check: % must be %, got %',
        v_bad.feature_key,
        v_expected_class[array_position(v_expected, v_bad.feature_key)],
        v_bad.enforcement_class;
    END IF;
  END LOOP;

  -- The published counts, so a future row added without a class decision
  -- cannot land silently (the verdict "X/11 server-enforced" lives or dies
  -- here). SCOPED to the known catalog: a historical row this file does not
  -- know about was conservatively classed above and must not make the
  -- published counts lie about the 11 client features. 12 rows = 11 client
  -- features + the 'tarot' alias.
  SELECT COUNT(*) INTO v_count
    FROM public.premium_feature_policy
   WHERE feature_key = ANY (v_expected)
     AND enforcement_class = 'server_enforced_data';
  IF v_count <> 3 THEN
    RAISE EXCEPTION 'JUNO-06 self-check: expected 3 server_enforced_data rows (tarot_cosmic, tarot_monthly, alias), got %', v_count;
  END IF;
  SELECT COUNT(*) INTO v_count
    FROM public.premium_feature_policy
   WHERE feature_key = ANY (v_expected)
     AND enforcement_class = 'server_metered_ui';
  IF v_count <> 7 THEN
    RAISE EXCEPTION 'JUNO-06 self-check: expected 7 server_metered_ui rows, got %', v_count;
  END IF;
  SELECT COUNT(*) INTO v_count
    FROM public.premium_feature_policy
   WHERE feature_key = ANY (v_expected)
     AND enforcement_class = 'public_content';
  IF v_count <> 2 THEN
    RAISE EXCEPTION 'JUNO-06 self-check: expected 2 public_content rows, got %', v_count;
  END IF;

  -- Validate the CHECK constraint over the rows that exist now.
  EXECUTE 'ALTER TABLE public.premium_feature_policy
             VALIDATE CONSTRAINT premium_feature_policy_enforcement_class_check';

  FOR v_bad IN
    SELECT feature_key, required_tier, free_preview_quota
      FROM public.premium_feature_policy
     WHERE feature_key IN ('daily_horoscope','monthly_horoscope','lucky_days',
                           'planetary_transits','retrograde_alerts',
                           'date_planner','tarot_monthly','tarot_cosmic')
  LOOP
    IF v_bad.free_preview_quota IS DISTINCT FROM 1 THEN
      RAISE EXCEPTION 'JUNO-06 self-check: % must keep a 1/day free preview, got %',
        v_bad.feature_key, v_bad.free_preview_quota;
    END IF;
  END LOOP;

  FOR v_bad IN
    SELECT feature_key, required_tier
      FROM public.premium_feature_policy
     WHERE feature_key IN ('monthly_horoscope','lucky_days',
                           'planetary_transits','retrograde_alerts',
                           'date_planner','tarot_cosmic')
  LOOP
    IF v_bad.required_tier NOT IN ('cosmic', 'premium_plus') THEN
      RAISE EXCEPTION 'JUNO-06 self-check: % must stay cosmic, got %',
        v_bad.feature_key, v_bad.required_tier;
    END IF;
  END LOOP;

  FOR v_bad IN
    SELECT feature_key, free_preview_quota
      FROM public.premium_feature_policy
     WHERE feature_key = 'synastry'
  LOOP
    IF v_bad.free_preview_quota IS NOT NULL THEN
      RAISE EXCEPTION 'JUNO-06 self-check: synastry must keep NULL preview (per-target contract lives in synastry_free_grant)';
    END IF;
  END LOOP;
END;
$$;

commit;
