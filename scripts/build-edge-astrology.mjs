#!/usr/bin/env node
// Generate the Deno-loadable synastry engine used by supabase/functions.
//
//   node scripts/build-edge-astrology.mjs            # write
//   node scripts/build-edge-astrology.mjs --check    # verify, write nothing
//
// WHY THIS SCRIPT EXISTS
// ----------------------
// `get-profile-chart` used to publish every placement's ecliptic longitude at
// full float64 precision, because the two clients computed the synastry
// themselves and `computeSynastry` needs longitudes. Those numbers inverted
// back to the target's exact birth instant and birth coordinates — the columns
// Phase 3-C revokes. (docs/security-audit-2026-09-07.md, JUNO-01.)
//
// The fix is to compute the synastry on the server and publish the RESULT
// instead of the INPUTS. The trap in that fix is obvious once stated: a
// hand-written Deno copy of the scoring model becomes a third implementation
// that drifts from the shared engine, silently, exactly like the two ephemeris
// copies `engine-contract.test.ts` had to be written to watch.
//
// So nothing is hand-written. esbuild bundles the real modules from
// `packages/shared/src/astrology`, and `--check` (wired into CI as
// `npm run validate:edge-astrology`) fails the build if the committed output
// no longer matches what the sources produce. Drift is not detected here — it
// is impossible.
//
// WHY THE OUTPUT IS COMMITTED RATHER THAN BUILT AT DEPLOY TIME
// ------------------------------------------------------------
// `supabase functions deploy` bundles whatever is on disk. A generated file
// that is not committed is a file that is absent on a colleague's machine and
// on a fresh clone, and the failure mode is a deployed function that cannot
// import its own engine. Committed + verified is the honest trade: the diff is
// noisy on the rare occasions the engine changes, and it is always correct.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = path.join(ROOT, 'packages/shared/src/astrology/edge-entry.ts');
const OUT = path.join(ROOT, 'supabase/functions/_shared/astrology-engine.generated.ts');

/** npm specifiers that must never survive into the bundle. */
const FORBIDDEN_IMPORTS = ['astronomy-engine', 'luxon', 'tz-lookup', '@supabase/supabase-js'];

const BANNER = `// @generated by scripts/build-edge-astrology.mjs — DO NOT EDIT.
//
// Source: packages/shared/src/astrology/edge-entry.ts and its imports.
// Regenerate: npm run build:edge-astrology
// Verify:     npm run validate:edge-astrology   (runs in CI; fails on drift)
//
// This is the SAME scoring model the web and mobile apps use, bundled for Deno
// so that get-profile-chart can compute a synastry server-side instead of
// publishing the longitudes it would need to compute one in the browser.
// See docs/security-audit-2026-09-07.md, JUNO-01.
//
// Editing this file by hand is pointless: CI regenerates it and compares.
// @ts-nocheck — generated output, type-checked at its source.
/* eslint-disable */
`;

async function build() {
  if (!existsSync(ENTRY)) {
    throw new Error(`Entry point missing: ${path.relative(ROOT, ENTRY)}`);
  }

  const { build: esbuild } = await import('esbuild');
  const result = await esbuild({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'esm',
    // `neutral` keeps Node and browser globals out of the output; Deno provides
    // neither `process` nor `window`, and a polyfill would be a silent bug.
    platform: 'neutral',
    target: 'es2022',
    // Nothing should be reachable, but declaring them external turns a
    // regression into a visible import line the assertion below catches,
    // instead of esbuild inlining an npm package into the bundle.
    external: FORBIDDEN_IMPORTS,
    legalComments: 'none',
    // Readable rather than minified: this file gets reviewed in diffs, and a
    // minified blob in a security-sensitive path is unreviewable.
    minify: false,
    charset: 'utf8',
  });

  const [file] = result.outputFiles;
  if (!file) throw new Error('esbuild produced no output');
  let code = file.text;

  // Assert the bundle is self-contained. `platform: 'neutral'` plus these
  // externals means a stray dependency shows up as a real import statement.
  for (const dep of FORBIDDEN_IMPORTS) {
    const pattern = new RegExp(`from\\s+["']${dep.replace(/[/\\^$*+?.()|[\]{}]/g, '\\$&')}["']`);
    if (pattern.test(code)) {
      throw new Error(
        `The edge bundle reached '${dep}'. Deno cannot resolve a bare npm specifier here.\n` +
        `Something in packages/shared/src/astrology/edge-entry.ts (or its imports) now pulls\n` +
        `it in. Move the pure part into its own module — this is exactly why\n` +
        `ZODIAC_SIGNS and placementToLongitude live in astrology/signs.ts.`,
      );
    }
  }
  if (/\bprocess\.env\b/.test(code) || /\brequire\(/.test(code)) {
    throw new Error('The edge bundle contains Node-only constructs (process.env / require).');
  }

  code = `${BANNER}\n${code.trimEnd()}\n`;
  return code;
}

const generated = await build();
const checkOnly = process.argv.includes('--check');
const sha = (s) => createHash('sha256').update(s, 'utf8').digest('hex').slice(0, 12);

if (checkOnly) {
  if (!existsSync(OUT)) {
    console.error(`✗ ${path.relative(ROOT, OUT)} is missing. Run: npm run build:edge-astrology`);
    process.exit(1);
  }
  const current = readFileSync(OUT, 'utf8');
  if (current !== generated) {
    console.error(
      `✗ ${path.relative(ROOT, OUT)} is stale.\n` +
      `  committed: ${sha(current)}   sources: ${sha(generated)}\n` +
      `  The shared synastry engine changed without the edge bundle being rebuilt, so the\n` +
      `  server and the clients would score the same two charts differently.\n` +
      `  Run: npm run build:edge-astrology`,
    );
    process.exit(1);
  }
  console.log(`✓ edge astrology bundle is current (${sha(current)}, ${current.length} bytes)`);
} else {
  mkdirSync(path.dirname(OUT), { recursive: true });
  const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (previous === generated) {
    console.log(`= unchanged (${sha(generated)})`);
  } else {
    writeFileSync(OUT, generated, 'utf8');
    console.log(
      `✓ wrote ${path.relative(ROOT, OUT)} (${sha(generated)}, ${generated.length} bytes)` +
      (previous ? ` — was ${sha(previous)}` : ''),
    );
  }
}
