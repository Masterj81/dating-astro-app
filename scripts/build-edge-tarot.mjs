#!/usr/bin/env node
// Generate the Deno-loadable tarot engine used by supabase/functions.
//
//   node scripts/build-edge-tarot.mjs            # write
//   node scripts/build-edge-tarot.mjs --check    # verify, write nothing
//
// Same contract as build-edge-astrology.mjs (JUNO-01's engine bundle): the
// edge function must draw with the EXACT shared engine — same seed, same
// shuffle, same meanings — so esbuild bundles packages/shared/src/tarot and
// --check (wired as validate:edge-tarot in CI) fails if the committed
// artifact is stale. Drift is not detected; it is impossible.
//
// JUNO-06 (2026-09-23): the reading became a server artifact so the corpus
// stops shipping in the APK. The artifact is COMMITTED for the same reason
// as the astrology bundle: `supabase functions deploy` bundles what is on
// disk, and an uncommitted generated file is an absent file on the next
// clone.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = path.join(ROOT, 'packages/shared/src/tarot/edge-entry.ts');
const OUT = path.join(
  ROOT,
  'supabase/functions/premium-tarot-reading/tarot.generated.ts',
);

const FORBIDDEN_IMPORTS = ['@supabase/supabase-js', 'astronomy-engine', 'luxon', 'tz-lookup'];

const BANNER = `// @generated by scripts/build-edge-tarot.mjs — DO NOT EDIT.
//
// Source: packages/shared/src/tarot/edge-entry.ts and its imports.
// Regenerate: npm run build:edge-tarot
// Verify:     npm run validate:edge-tarot
//
// The premium-tarot-reading edge draws with the EXACT shared engine. This
// bundle exists so the tarot corpus and shuffle can leave the mobile bundle
// (JUNO-06) without the server growing a second, drifting implementation.
`;

function sha(text) {
  return createHash('sha256').update(text).digest('hex').slice(0, 12);
}

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  charset: 'utf8',
  minify: false,
  legalComments: 'none',
  logLevel: 'silent',
});

let generated = BANNER + '\n' + result.outputFiles[0].text;

for (const spec of FORBIDDEN_IMPORTS) {
  if (new RegExp(`from ['"]${spec.replace(/[/@]/g, '\\$&')}`).test(generated)) {
    console.error(`✗ bundle still imports ${spec} — the tarot artifact must be dependency-free`);
    process.exit(1);
  }
}

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) {
    console.error(`✗ ${path.relative(ROOT, OUT)} does not exist. Run: npm run build:edge-tarot`);
    process.exit(1);
  }
  const current = readFileSync(OUT, 'utf8');
  if (current !== generated) {
    console.error(
      `✗ ${path.relative(ROOT, OUT)} is stale.\n` +
        `  committed: ${sha(current)}   sources: ${sha(generated)}\n` +
        `  The shared tarot engine changed without the edge artifact being rebuilt.\n` +
        `  Run: npm run build:edge-tarot`,
    );
    process.exit(1);
  }
  console.log(`✓ edge tarot artifact is current (${sha(current)}, ${current.length} bytes)`);
} else {
  mkdirSync(path.dirname(OUT), { recursive: true });
  const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (previous === generated) {
    console.log(`= unchanged (${sha(generated)})`);
  } else {
    writeFileSync(OUT, generated, 'utf8');
    console.log(
      `✓ wrote ${path.relative(ROOT, OUT)} (${sha(generated)}, ${generated.length} bytes)` +
        (previous ? ` — was ${sha(previous)}` : ''),
    );
  }
}
